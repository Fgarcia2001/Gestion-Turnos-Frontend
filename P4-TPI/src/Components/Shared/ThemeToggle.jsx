// Toggle de modo claro/oscuro, mismo estilo que el selector de idioma que ya
// existe en cada seccion (pill blanca con borde, ES|EN style).
const ThemeToggle = ({ className = "" }) => {
  const { theme, toggleTheme } = useTheme();
  const isDark = theme === "dark";

  return (
    <button
      type="button"
      onClick={toggleTheme}
      aria-label={isDark ? "Switch to light mode" : "Switch to dark mode"}
      title={isDark ? "Light mode" : "Dark mode"}
      className={`flex items-center justify-center w-9 h-9 rounded-full border bg-[var(--surface)] text-[var(--text-primary)] shadow-sm hover:bg-[var(--surface-muted)] transition-all ${className}`}
      style={{ borderColor: "var(--border-subtle)" }}
    >
      {isDark ? <IconSun /> : <IconMoon />}
    </button>
  );
};

export default ThemeToggle;
